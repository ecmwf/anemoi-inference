def main(argv: list[str] | None = None) -> int:
    """Entry point of the command line interface.

    Parameters
    ----------
    argv : list[str] | None
        Command line arguments.

    Returns
    -------
    int
        Exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_build = sub.add_parser("build", help="Write the HTML page.")
    p_build.add_argument("-o", "--output", type=Path, default=ROOT.parent / "_build" / "config-reference")

    sub.add_parser("check", help="Check specs and examples against the code.")

    p_gen = sub.add_parser("generate", help="Regenerate draft specs from the code.")
    p_gen.add_argument("--check", action="store_true", help="Only report files that are out of date.")

    p_skel = sub.add_parser("skeleton", help="Print the spec that would be generated for one component.")
    p_skel.add_argument("kind")
    p_skel.add_argument("name")

    p_intro = sub.add_parser("introspect", help="Show what the code says about a component.")
    p_intro.add_argument("kind")
    p_intro.add_argument("name")

    args = parser.parse_args(argv)

    if args.command == "build":
        print(build(args.output))
        return 0

    if args.command == "check":
        errors = check_all()
        for e in errors:
            print(e)
        print(f"{len(errors)} problem(s)", file=sys.stderr)
        return 1 if errors else 0

    if args.command == "introspect":
        intro = introspect(args.kind, args.name)
        print(f"{intro.kind}/{intro.name} -> {intro.target}")
        print(
            f"  main argument: {intro.main_argument}  *args: {intro.var_positional}  "
            f"**kwargs: {intro.var_kwargs}  aliases: {intro.aliases}"
        )
        for p in intro.params.values():
            default = "REQUIRED" if p.required else repr(p.default)
            print(f"  {p.name}: {p.annotation} = {default}\n      {p.doc}")
        return 0

    if args.command == "generate":
        changes = generate(write=not args.check)
        for c in changes:
            print(c)
        stale = check_curated()
        if stale:
            print("Curated specs not regenerated; update them by hand:", file=sys.stderr)
            for p in stale:
                print(f"  {p}", file=sys.stderr)
        if args.check and changes:
            print("Out of date: run `refgen.py generate`", file=sys.stderr)
            return 1
        return 0

    if args.command == "skeleton":
        print(skeleton(args.kind, args.name))
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
