def _is_literal(value: Any) -> bool:
    if isinstance(value, (bool, int, float, str)) or value is None:
        return True
    if isinstance(value, (list, tuple)):
        return all(_is_literal(v) for v in value)
    if isinstance(value, dict):
        return all(isinstance(k, str) and _is_literal(v) for k, v in value.items())
    return False


def _same_default(a: Any, b: Any) -> bool:
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    if isinstance(b, tuple):
        b = list(b)
    return type(a) is type(b) and a == b


def documented_kinds() -> list[str]:
    """List the kinds that are backed by a registry.

    Returns
    -------
    list[str]
        Kind names from ``index.yaml``.
    """
    return [k for k, v in load_index()["kinds"].items() if v.get("registry")]


def check_coverage(kind: str, specs: dict[str, dict[str, dict[str, Any]]]) -> list[str]:
    """Check that every registered component of ``kind`` is documented or explicitly excluded.

    Parameters
    ----------
    kind : str
        The component kind.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs.

    Returns
    -------
    list[str]
        Problems found.
    """
    errors = []
    registry = get_registry(kind)
    excluded = {normalise(n) for n in (load_index()["kinds"][kind].get("exclude") or {})}
    documented = {normalise(s["name"]) for k, s in specs.get(kind, {}).items() if not k.startswith("_")}
    for name in registry.registered:
        if name not in documented and name not in excluded:
            errors.append(f"{kind}/{name}: registered but not documented (run `refgen.py generate`)")
    for name in documented:
        if name not in registry.registered:
            errors.append(f"{kind}/{name}: documented but not registered")
    for name in excluded & documented:
        errors.append(f"{kind}/{name}: both documented and excluded")
    return errors


def check_spec(kind: str, key: str, specs: dict[str, dict[str, dict[str, Any]]]) -> list[str]:
    """Check a component spec against the code.

    Parameters
    ----------
    kind : str
        The component kind.
    key : str
        The spec file stem.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs.

    Returns
    -------
    list[str]
        Problems found.
    """
    spec = specs[kind][key]
    where = spec["_path"]
    errors = [f"{where}: unknown key '{k}'" for k in spec if k not in SPEC_KEYS and not k.startswith("_")]
    fields = resolve_fields(spec, specs)
    for fname, f in fields.items():
        errors += [
            f"{where}: field '{fname}' has unknown key '{k}'" for k in f if k not in FIELD_KEYS | {"inherited_from"}
        ]
        if not f.get("description") and spec.get("status") in CURATED:
            errors.append(f"{where}: field '{fname}' has no description")
        if f.get("ref") and f["ref"] not in load_index()["kinds"]:
            errors.append(f"{where}: field '{fname}' refers to unknown kind '{f['ref']}'")
    if not spec.get("summary") and (key.startswith("_") or spec.get("status") in CURATED):
        errors.append(f"{where}: missing summary")
    if "TODO" in json.dumps({k: v for k, v in spec.items() if not k.startswith("_")}, default=str):
        errors.append(f"{where}: contains TODO")
    if spec.get("status", "draft") not in STATUSES:
        errors.append(f"{where}: `status` must be one of {', '.join(STATUSES)}")
    if key.startswith("_"):
        return errors

    intro = introspect(kind, spec["name"])
    hidden = set(spec.get("hidden") or [])
    for pname, param in intro.params.items():
        if pname in hidden:
            continue
        if pname not in fields:
            errors.append(f"{where}: parameter '{pname}' is in the code but not documented (or listed in `hidden`)")
            continue
        f = fields[pname]
        if param.required and not f.get("required"):
            errors.append(f"{where}: field '{pname}' is required in the code but not marked `required: true`")
        if (
            not param.required
            and param.default is not None
            and _is_literal(param.default)
            and "default_text" not in f
            and not _same_default(f.get("default", MISSING), param.default)
        ):
            errors.append(
                f"{where}: field '{pname}' default is {param.default!r} in the code but "
                f"{f.get('default', 'not stated')!r} in the spec (set `default` or `default_text`)"
            )
    for fname in fields:
        if fname == intro.var_positional:
            continue
        if fname not in intro.params and not intro.var_kwargs and fname not in hidden:
            errors.append(f"{where}: field '{fname}' is documented but not accepted by the code")
    expected_positional = intro.main_argument or intro.var_positional
    if expected_positional and spec.get("positional") != expected_positional:
        errors.append(f"{where}: `positional` should be '{expected_positional}'")
    if intro.var_positional and intro.var_positional not in fields:
        errors.append(f"{where}: positional list '{intro.var_positional}' must be documented as a field")
    if spec.get("extra_fields") and not intro.var_kwargs:
        errors.append(f"{where}: `extra_fields` is set but the code does not accept extra keyword arguments")
    for alias in intro.aliases:
        if alias not in {normalise(a) for a in spec.get("aliases", [])}:
            errors.append(f"{where}: alias '{alias}' is registered but not listed in `aliases`")
    return errors


@dataclass
class Usage:
    """A component found while walking a configuration.

    Attributes
    ----------
    kind : str
        Component kind.
    name : str
        Name as written in the configuration.
    location : str
        Dotted location in the configuration.
    args : list[Any]
        Positional values (short form).
    kwargs : dict[str, Any]
        Keyword values.
    """

    kind: str
    name: str
    location: str
    args: list[Any]
    kwargs: dict[str, Any]


def _split_component(value: Any) -> tuple[str, list[Any], dict[str, Any]] | None:
    """Split a component configuration into name, positional and keyword arguments, mirroring ``Registry.from_config``."""
    if isinstance(value, str):
        return value, [], {}
    if isinstance(value, dict) and "_type" in value:
        rest = dict(value)
        return rest.pop("_type"), [], rest
    if isinstance(value, dict) and len(value) == 1:
        name, inner = next(iter(value.items()))
        if isinstance(inner, dict):
            return name, [], dict(inner)
        if isinstance(inner, list):
            return name, list(inner), {}
        if inner is None:
            return name, [], {}
        return name, [inner], {}
    return None


def walk(
    value: Any,
    kind: str,
    specs: dict[str, dict[str, dict[str, Any]]],
    location: str,
    errors: list[str],
    usages: list[Usage],
    *,
    many: bool = False,
    per_dataset: bool = False,
) -> None:
    """Walk a component slot, recording usages and problems.

    Parameters
    ----------
    value : Any
        The configuration value of the slot.
    kind : str
        The kind expected in the slot.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs.
    location : str
        Dotted location, for messages.
    errors : list[str]
        Problems are appended here.
    usages : list[Usage]
        Components found are appended here.
    many : bool
        Whether the slot holds a list of components.
    per_dataset : bool
        Whether the slot may be keyed by dataset name.
    """
    if value is None:
        return
    if per_dataset and isinstance(value, dict) and value:
        first = next(iter(value))
        is_component = "_type" in value or (len(value) == 1 and find_spec(specs, kind, str(first)) is not None)
        if not is_component and not (many and isinstance(value, list)):
            for dataset, sub in value.items():
                walk(sub, kind, specs, f"{location}.{dataset}", errors, usages, many=many)
            return
    if many:
        if not isinstance(value, list):
            errors.append(f"{location}: expected a list")
            return
        for i, item in enumerate(value):
            walk(item, kind, specs, f"{location}[{i}]", errors, usages)
        return

    split = _split_component(value)
    if split is None:
        errors.append(f"{location}: cannot read a {kind} component from {value!r}")
        return
    name, args, kwargs = split
    spec = find_spec(specs, kind, name)
    if spec is None:
        errors.append(f"{location}: unknown {kind} '{name}'")
        return
    usages.append(Usage(kind=kind, name=spec["name"], location=location, args=args, kwargs=kwargs))
    check_arguments(spec, kind, args, kwargs, specs, f"{location}.{name}", errors, usages)


def check_arguments(
    spec: dict[str, Any],
    kind: str,
    args: list[Any],
    kwargs: dict[str, Any],
    specs: dict[str, dict[str, dict[str, Any]]],
    location: str,
    errors: list[str],
    usages: list[Usage],
) -> None:
    """Check component arguments against its spec and the code, then walk nested component slots.

    Parameters
    ----------
    spec : dict[str, Any]
        The component spec.
    kind : str
        The component kind.
    args : list[Any]
        Positional values.
    kwargs : dict[str, Any]
        Keyword values.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs.
    location : str
        Dotted location, for messages.
    errors : list[str]
        Problems are appended here.
    usages : list[Usage]
        Components found are appended here.
    """
    fields = resolve_fields(spec, specs)
    intro = None
    if kind != TOP_LEVEL_KIND:
        try:
            intro = introspect(kind, spec["name"])
        except Exception as e:  # noqa: BLE001 - check_spec reports import failures; the page still builds
            errors.append(f"{location}: cannot introspect '{spec['name']}': {e}")
    values = dict(kwargs)
    if args:
        positional = spec.get("positional")
        if positional and intro and positional == intro.var_positional:
            values[positional] = args
        elif positional and len(args) == 1:
            values[positional] = args[0]
        else:
            errors.append(f"{location}: short form with {args!r} is not accepted (no `positional` in spec)")
    for key, val in values.items():
        f = fields.get(key)
        if f is None:
            if not (intro and intro.var_kwargs) and key not in (spec.get("hidden") or []):
                errors.append(f"{location}: unknown field '{key}'")
            continue
        if f.get("choices") and val not in f["choices"]:
            errors.append(f"{location}.{key}: {val!r} is not one of {f['choices']}")
        if f.get("ref"):
            walk(
                val,
                f["ref"],
                specs,
                f"{location}.{key}",
                errors,
                usages,
                many=bool(f.get("many")),
                per_dataset=bool(f.get("per_dataset")),
            )
        elif f.get("nested") and isinstance(val, dict):
            nested_spec = {"name": key, "fields": f["nested"]}
            check_arguments(nested_spec, TOP_LEVEL_KIND, [], val, specs, f"{location}.{key}", errors, usages)
    for key, f in fields.items():
        if f.get("required") and key not in values:
            errors.append(f"{location}: missing required field '{key}'")


def check_example(example: Example, specs: dict[str, dict[str, dict[str, Any]]]) -> tuple[list[str], list[Usage]]:
    """Validate an example configuration.

    The example must load as a :class:`RunConfiguration` and every component in it must match its spec and code.

    Parameters
    ----------
    example : Example
        The example.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs.

    Returns
    -------
    tuple[list[str], list[Usage]]
        Problems found and the components used.
    """
    from anemoi.inference.config.run import RunConfiguration

    errors: list[str] = []
    usages: list[Usage] = []
    where = f"examples/{example.path}"
    if not isinstance(example.data, dict):
        return [f"{where}: not a mapping"], usages
    try:
        RunConfiguration.model_validate(example.data)
    except Exception as e:  # noqa: BLE001 - report any validation failure
        errors.append(f"{where}: RunConfiguration rejects it: {e}")
    top = specs[TOP_LEVEL_KIND][TOP_LEVEL_NAME]
    check_arguments(top, TOP_LEVEL_KIND, [], example.data, specs, where, errors, usages)
    return errors, usages


def check_all() -> list[str]:
    """Run every check.

    Returns
    -------
    list[str]
        All problems found.
    """
    specs = load_specs()
    errors: list[str] = []
    for kind in documented_kinds():
        errors += check_coverage(kind, specs)
    for kind, entries in specs.items():
        for key in entries:
            errors += check_spec(kind, key, specs)
    for example in load_examples():
        errors += check_example(example, specs)[0]
    return errors


