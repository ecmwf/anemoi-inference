class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def _clean_type(text: str) -> str:
    """Shorten an annotation for readers: drop module paths and ``NoneType``."""
    text = re.sub(r"\b(?:[a-z_][\w]*\.)+([A-Za-z_]\w*)", r"\1", text)
    text = re.sub(r"Union\[(.*)\]$", lambda m: m.group(1).replace(", ", " | "), text)
    text = text.replace("Optional[", "").replace("NoneType", "None")
    parts = [p.strip() for p in text.split(" | ") if p.strip() not in ("None", "")]
    return " | ".join(parts) or "any"


def _field_ref(kind: str, name: str, param: str) -> dict[str, Any] | None:
    refs = load_index().get("field_refs") or {}
    return refs.get(f"{kind}/{name}.{param}") or refs.get(f"{kind}.{param}") or refs.get(param)


def skeleton(kind: str, name: str, stem: str | None = None) -> str:
    """Generate a draft spec for a component from its code.

    Fields shared with a ``_<set>.yaml`` file of the same kind are replaced by ``inherits``, fields that take other
    components get a ``ref`` from ``field_refs`` in ``index.yaml``, and parameters listed in the kind's ``hidden``
    are not documented.

    Parameters
    ----------
    kind : str
        The component kind.
    name : str
        The registered name.
    stem : str | None
        File stem of the spec, used in the header. Defaults to the registered name.

    Returns
    -------
    str
        The YAML text of the draft spec.
    """
    intro = introspect(kind, name)
    meta = load_index()["kinds"].get(kind, {})
    specs = load_specs()
    spec: dict[str, Any] = {"name": name if kind == TOP_LEVEL_KIND else normalise(name), "status": "draft"}
    if intro.summary:
        spec["summary"] = intro.summary
    if intro.aliases:
        spec["aliases"] = intro.aliases
    if intro.main_argument or intro.var_positional:
        spec["positional"] = intro.main_argument or intro.var_positional

    params = dict(intro.params)
    inherits = []
    for stem_, shared in sorted(specs.get(kind, {}).items()):
        shared_fields = set((shared.get("fields") or {}).keys())
        if stem_.startswith("_") and shared_fields and shared_fields <= set(params):
            inherits.append(f"{kind}/{stem_}")
            for f in shared_fields:
                # Keep a local copy when the code is stricter than the shared description.
                if not (params[f].required and not shared["fields"][f].get("required")):
                    params.pop(f)
    if inherits:
        spec["inherits"] = inherits

    fields: dict[str, Any] = {}
    if intro.var_positional:
        fields[intro.var_positional] = {"type": "list", "description": "Values given in the short `name: [...]` form."}
        ref = _field_ref(kind, name, intro.var_positional)
        if ref:
            fields[intro.var_positional].update(ref)
    hidden = [p for p in meta.get("hidden") or [] if p in params]
    for p in params.values():
        if p.name in hidden:
            continue
        f: dict[str, Any] = {"type": _clean_type(p.annotation) if p.annotation else "any"}
        ref = _field_ref(kind, name, p.name)
        if ref:
            f.update(ref)
        if p.required:
            f["required"] = True
        elif p.default is not None and _is_literal(p.default):
            f["default"] = list(p.default) if isinstance(p.default, tuple) else p.default
        elif p.default is not None:
            f["default_text"] = repr(p.default)
        if p.doc:
            f["description"] = p.doc
        fields[p.name] = f
    spec["fields"] = fields
    if hidden:
        spec["hidden"] = hidden
    if intro.var_kwargs:
        spec["extra_fields"] = "Other options are passed on unchanged to the underlying implementation."
    header = (
        f"{GENERATED_MARK} from {intro.target}.\n"
        f"# Regenerated while `status: draft`. Set `status: AI-reviewed` or `reviewed` before editing by hand.\n"
    )
    return header + yaml.dump(spec, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)


def generate(write: bool) -> list[str]:
    """Regenerate draft specs from the code.

    A spec is (re)generated when it is missing or has ``status: draft``.

    Parameters
    ----------
    write : bool
        Write changes to disk. If False, only report what would change.

    Returns
    -------
    list[str]
        Paths that are (or would be) created or updated.
    """
    index = load_index()
    changes: list[str] = []

    def put(path: Path, text: str) -> None:
        if path.exists() and path.read_text() == text:
            return
        changes.append(str(path.relative_to(ROOT)))
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    for kind in documented_kinds():
        excluded = {normalise(n) for n in (index["kinds"][kind].get("exclude") or {})}
        for name in get_registry(kind).registered:
            if name in excluded:
                continue
            spec = find_spec(load_specs(), kind, name)
            # Only drafts are regenerated. Curated specs and unknown statuses (typos) are reported by check_curated.
            if spec is not None and spec.get("status", "draft") != "draft":
                continue
            stem = Path(spec["_path"]).stem if spec else name
            put(COMPONENTS_DIR / kind / f"{stem}.yaml", skeleton(kind, name, stem))
    return changes


def check_curated() -> list[str]:
    """Check the specs that :func:`generate` leaves alone (curated, or with an unknown status) against the code.

    Returns
    -------
    list[str]
        Problems found, each prefixed with the spec's status.
    """
    specs = load_specs()
    problems = []
    for kind, entries in specs.items():
        for key, spec in entries.items():
            if not key.startswith("_") and spec.get("status", "draft") != "draft":
                problems += [f"({spec['status']}) {p}" for p in check_spec(kind, key, specs)]
    return problems


