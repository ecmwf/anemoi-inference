def _inline_md(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"``([^`]+)``|`([^`]+)`", lambda m: f"<code>{m.group(1) or m.group(2)}</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*([^*\s][^*]*)\*", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    return text


def markdown(text: str | None) -> str:
    """Render the small Markdown subset used in specs.

    Supports paragraphs, bullet lists, fenced code blocks, inline code, bold, italics and links.

    Parameters
    ----------
    text : str | None
        Markdown text.

    Returns
    -------
    str
        HTML.
    """
    if not text:
        return ""
    out: list[str] = []
    para: list[str] = []
    items: list[str] = []
    lines = text.strip("\n").splitlines()

    def flush() -> None:
        if para:
            out.append(f"<p>{_inline_md(' '.join(para))}</p>")
            para.clear()
        if items:
            out.append("<ul>" + "".join(f"<li>{_inline_md(i)}</li>" for i in items) + "</ul>")
            items.clear()

    i = 0
    while i < len(lines):
        line = lines[i]
        if line.strip().startswith("```"):
            flush()
            lang = line.strip()[3:].strip() or "text"
            block = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                block.append(lines[i])
                i += 1
            out.append(highlight("\n".join(block), lang))
        elif re.match(r"^\s*[-*] ", line):
            if para:
                flush()
            items.append(re.sub(r"^\s*[-*] ", "", line))
        elif items and line.startswith("  ") and line.strip():
            items[-1] += " " + line.strip()
        elif not line.strip():
            flush()
        else:
            if items:
                flush()
            para.append(line.strip())
        i += 1
    flush()
    return "".join(out)


def highlight(code: str, lang: str = "yaml") -> str:
    """Highlight code with Pygments, falling back to plain escaped text.

    Parameters
    ----------
    code : str
        Source code.
    lang : str
        Pygments lexer name.

    Returns
    -------
    str
        HTML.
    """
    try:
        from pygments import highlight as _highlight
        from pygments.formatters import HtmlFormatter
        from pygments.lexers import get_lexer_by_name

        return _highlight(code, get_lexer_by_name(lang), HtmlFormatter(nowrap=False, cssclass="hl"))
    except Exception:  # noqa: BLE001 - highlighting is cosmetic
        return f'<div class="hl"><pre>{html.escape(code)}</pre></div>'


def _json_default(value: Any) -> Any:
    if value is MISSING:
        return None
    return str(value)


def collect_site_data() -> dict[str, Any]:
    """Gather everything the page needs into one JSON-serialisable structure.

    Returns
    -------
    dict[str, Any]
        Kinds, components (with rendered descriptions and resolved fields) and examples.
    """
    index = load_index()
    specs = load_specs()
    examples = load_examples()

    usage_map: dict[str, list[str]] = {}
    example_data = []
    for ex in examples:
        _, usages = check_example(ex, specs)
        ids = sorted({f"{u.kind}/{u.name}" for u in usages})
        for cid in ids:
            usage_map.setdefault(cid, []).append(ex.path)
        example_data.append(
            {
                "id": ex.path,
                "title": ex.title,
                "description": markdown(ex.description),
                "html": highlight(ex.text),
                "text": ex.text,
                "data": ex.data,
                "components": ids,
            }
        )

    kinds = []
    components = {}
    for kind, meta in index["kinds"].items():
        names = []
        for key, spec in sorted(specs.get(kind, {}).items()):
            if key.startswith("_"):
                continue
            cid = f"{kind}/{spec['name']}"
            names.append(spec["name"])
            fields = []
            for fname, f in resolve_fields(spec, specs).items():
                default = f.get("default", MISSING)
                fields.append(
                    {
                        "name": fname,
                        "type": f.get("type", ""),
                        "required": bool(f.get("required")),
                        "hasDefault": default is not MISSING,
                        "default": None if default is MISSING else default,
                        "defaultText": f.get("default_text"),
                        "description": markdown(f.get("description")),
                        "example": f.get("example"),
                        "choices": f.get("choices"),
                        "ref": f.get("ref"),
                        "many": bool(f.get("many")),
                        "perDataset": bool(f.get("per_dataset")),
                        "nested": bool(f.get("nested")),
                        "inheritedFrom": f.get("inherited_from"),
                    }
                )
            components[cid] = {
                "id": cid,
                "kind": kind,
                "name": spec["name"],
                "title": spec.get("title") or spec["name"],
                "summary": _inline_md(spec.get("summary", "")),
                "description": markdown(spec.get("description")),
                "notes": markdown(spec.get("notes")),
                "status": spec.get("status", "draft"),
                "aliases": spec.get("aliases", []),
                "positional": spec.get("positional"),
                "extraFields": markdown(spec.get("extra_fields")),
                "seeAlso": spec.get("see_also", []),
                "fields": fields,
                "examples": usage_map.get(cid, []),
            }
        kinds.append(
            {
                "id": kind,
                "title": meta["title"],
                "summary": _inline_md(meta.get("summary", "")),
                "description": markdown(meta.get("description")),
                "slot": meta.get("slot"),
                "path": meta.get("path"),
                "components": names,
            }
        )
    page = index.get("page") or {}
    return {
        "page": {
            "package": page["package"],
            "title": page.get("title", f"{page['package']} configuration reference"),
            "description": page.get("description", ""),
            "configFile": page.get("config_file", "config.yaml"),
            "validateCommand": page.get("validate_command"),
            "notice": markdown(page.get("notice")),
            "docsLink": page.get("docs_link"),
        },
        "top": f"{TOP_LEVEL_KIND}/{TOP_LEVEL_NAME}",
        "kinds": kinds,
        "components": components,
        "examples": example_data,
        "intro": markdown(index.get("intro")),
    }


def build(outdir: Path) -> Path:
    """Write the self-contained HTML page.

    Parameters
    ----------
    outdir : Path
        Output directory. Created if needed.

    Returns
    -------
    Path
        Path of the written ``index.html``.
    """
    from pygments.formatters import HtmlFormatter

    data = collect_site_data()
    template = (SITE_DIR / "template.html").read_text()
    css = (SITE_DIR / "style.css").read_text()
    css += "\n" + HtmlFormatter(style="friendly").get_style_defs(".hl")
    css += "\n@media (prefers-color-scheme: dark) {\n"
    css += HtmlFormatter(style="github-dark").get_style_defs(":root:not([data-theme='light']) .hl")
    css += "\n}\n"
    css += HtmlFormatter(style="github-dark").get_style_defs(":root[data-theme='dark'] .hl")
    js = (SITE_DIR / "app.js").read_text()
    payload = json.dumps(data, default=_json_default, separators=(",", ":")).replace("</", "<\\/")
    meta = data["page"]
    # Identity first, so placeholders in the CSS, JS or data are never substituted.
    page = template
    for key, value in {
        "__TITLE__": meta["title"],
        "__DESCRIPTION__": meta["description"],
        "__PACKAGE__": meta["package"],
        "__CONFIG_FILE__": meta["configFile"],
        "__VERSION__": _version(meta["package"]),
    }.items():
        page = page.replace(key, html.escape(value))
    page = page.replace("/*__CSS__*/", css).replace("/*__JS__*/", js).replace('"__DATA__"', payload)
    outdir.mkdir(parents=True, exist_ok=True)
    target = outdir / "index.html"
    target.write_text(page)
    return target


def _version(package: str) -> str:
    try:
        return importlib.metadata.version(package)
    except importlib.metadata.PackageNotFoundError:
        return "unknown"


