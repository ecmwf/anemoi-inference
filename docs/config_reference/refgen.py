@dataclass
class Param:
    """A user-settable constructor parameter.

    Attributes
    ----------
    name : str
        Parameter name.
    annotation : str
        Type annotation as text.
    required : bool
        Whether the parameter has no default.
    default : Any
        The default value, or ``MISSING``.
    doc : str
        Description from the NumPy docstring or attribute docstring.
    """

    name: str
    annotation: str
    required: bool
    default: Any
    doc: str = ""


@dataclass
class Introspected:
    """What the code says about a component.

    Attributes
    ----------
    kind : str
        Component kind.
    name : str
        Registered name.
    target : str
        Dotted path of the class.
    summary : str
        First paragraph of the class docstring.
    params : dict[str, Param]
        User-settable parameters, following ``**kwargs`` forwarded to base classes.
    var_kwargs : bool
        Whether unknown keyword arguments are accepted.
    main_argument : str | None
        Parameter set by the short ``name: value`` form.
    var_positional : str | None
        Name of the ``*args`` parameter, set by the short ``name: [...]`` form.
    aliases : list[str]
        Alternative registered names.
    """

    kind: str
    name: str
    target: str
    summary: str
    params: dict[str, Param] = field(default_factory=dict)
    var_kwargs: bool = False
    main_argument: str | None = None
    var_positional: str | None = None
    aliases: list[str] = field(default_factory=list)


def get_registry(kind: str) -> Any:
    """Import the registry declared for ``kind`` in ``index.yaml``.

    Parameters
    ----------
    kind : str
        The component kind.

    Returns
    -------
    Any
        The registry object.
    """
    module, _, attr = load_index()["kinds"][kind]["registry"].partition(":")
    return getattr(importlib.import_module(module), attr)


def _parse_numpy_params(doc: str | None) -> dict[str, str]:
    """Extract ``Parameters`` entries from a NumPy-style docstring."""
    if not doc:
        return {}
    lines = inspect.cleandoc(doc).splitlines()
    out: dict[str, str] = {}
    in_params = False
    current: str | None = None
    for i, line in enumerate(lines):
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        if re.fullmatch(r"-{3,}", nxt.strip()) and line.strip():
            in_params = line.strip() in ("Parameters", "Other Parameters")
            current = None
            continue
        if not in_params or re.fullmatch(r"-{3,}", line.strip()):
            continue
        m = re.match(r"^(\*{0,2}\w+)\s*:?", line)
        if m and not line.startswith(" "):
            current = m.group(1).lstrip("*")
            out[current] = ""
        elif current and line.strip():
            out[current] = (out[current] + " " + line.strip()).strip()
    return out


def _summary(doc: str | None) -> str:
    if not doc:
        return ""
    return inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " ").strip()


def _super_call(func: Any, kwargs_name: str) -> set[str] | None:
    """Find a ``super().__init__`` call forwarding ``**kwargs_name``.

    Returns the keyword names the call sets explicitly, or None if ``**kwargs_name`` is not forwarded.
    """
    try:
        source = textwrap.dedent(inspect.getsource(func))
    except (OSError, TypeError):
        return None
    for m in re.finditer(r"super\([^)]*\)\.__init__\(", source):
        depth, i = 1, m.end()
        while i < len(source) and depth:
            depth += {"(": 1, ")": -1}.get(source[i], 0)
            i += 1
        call = source[m.end() : i]
        if f"**{kwargs_name}" in call:
            return set(re.findall(r"(?<![\w.*])(\w+)\s*=(?!=)", call))
    return None


def _main_argument(cls: type) -> str | None:
    from anemoi.inference.decorators import main_argument

    for klass in cls.__mro__:
        init = klass.__dict__.get("__init__")
        for cell in getattr(init, "__closure__", None) or ():
            try:
                value = cell.cell_contents
            except ValueError:
                continue
            if isinstance(value, main_argument):
                return value.name
    return None


def _annotation(param: inspect.Parameter) -> str:
    if param.annotation is inspect.Parameter.empty:
        return ""
    text = param.annotation if isinstance(param.annotation, str) else inspect.formatannotation(param.annotation)
    return text.replace("typing.", "")


def introspect_component(kind: str, name: str) -> Introspected:
    """Collect the user-settable parameters of a registered component.

    Parameters
    ----------
    kind : str
        The component kind.
    name : str
        The registered name.

    Returns
    -------
    Introspected
        The parameters, following ``**kwargs`` forwarded to base classes.
    """
    registry = get_registry(kind)
    cls = registry.lookup(name)
    canonical = normalise(name)
    aliases = sorted(normalise(a) for a in registry.aliases().get(canonical, []))

    injected = INJECTED_PARAMS | set(load_index()["kinds"][kind].get("injected") or [])
    real = next(
        (
            k
            for k in cls.__mro__
            if k.__name__ != "WrappedClass" and k.__module__ not in ("abc", "anemoi.inference.decorators")
        ),
        cls,
    )
    result = Introspected(
        kind=kind,
        name=canonical,
        target=f"{real.__module__}.{real.__qualname__}",
        summary=_summary(real.__doc__),
        main_argument=_main_argument(cls),
        aliases=aliases,
    )
    docs: dict[str, str] = {}
    set_by_child: set[str] = set()
    for klass in cls.__mro__:
        if klass is object:
            break
        func = klass.__dict__.get("__new__") or klass.__dict__.get("__init__")
        if func is None:
            continue
        if isinstance(func, staticmethod):
            func = func.__func__
        docs = {**_parse_numpy_params(func.__doc__), **_parse_numpy_params(klass.__doc__), **docs}
        sig = inspect.signature(func)
        var_kw: str | None = None
        is_wrapper = klass.__name__ == "WrappedClass"
        for p in sig.parameters.values():
            if p.kind == p.VAR_KEYWORD:
                var_kw = p.name
                continue
            if p.kind == p.VAR_POSITIONAL:
                if not is_wrapper and result.var_positional is None and not set_by_child:
                    result.var_positional = p.name
                continue
            if p.name in injected or p.name.startswith("_") or p.name in result.params or p.name in set_by_child:
                continue
            result.params[p.name] = Param(
                name=p.name,
                annotation=_annotation(p),
                required=p.default is inspect.Parameter.empty,
                default=MISSING if p.default is inspect.Parameter.empty else p.default,
            )
        if var_kw is None:
            result.var_kwargs = False
            break
        if is_wrapper:
            continue
        explicit = _super_call(func, var_kw) if klass.__dict__.get("__init__") is func else None
        if explicit is not None:
            set_by_child |= explicit
            continue
        result.var_kwargs = True
        break
    for key, default in _kwargs_reads(cls).items():
        if key not in result.params and key not in injected:
            result.params[key] = Param(name=key, annotation="", required=False, default=default)
    for p in result.params.values():
        p.doc = docs.get(p.name, "")
    return result


def _kwargs_reads(cls: type) -> dict[str, Any]:
    """Find options read with ``kwargs.pop("name", default)`` or ``kwargs.get(...)`` in constructors."""
    found: dict[str, Any] = {}
    for klass in cls.__mro__:
        func = klass.__dict__.get("__init__")
        if func is None or klass.__name__ == "WrappedClass":
            continue
        try:
            tree = ast.parse(textwrap.dedent(inspect.getsource(func)))
        except (OSError, TypeError, SyntaxError):
            continue
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in ("pop", "get")
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "kwargs"
                and node.args
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[0].value, str)
            ):
                default: Any = None
                if len(node.args) > 1:
                    try:
                        default = ast.literal_eval(node.args[1])
                    except ValueError:
                        default = None
                found.setdefault(node.args[0].value, default)
    return found


def _attribute_docstrings(model: type) -> dict[str, str]:
    """Read attribute docstrings (string literals following annotated assignments) from a class and its bases."""
    out: dict[str, str] = {}
    for klass in reversed(model.__mro__):
        try:
            tree = ast.parse(textwrap.dedent(inspect.getsource(klass)))
        except (OSError, TypeError):
            continue
        body = tree.body[0].body if tree.body and isinstance(tree.body[0], ast.ClassDef) else []
        for node, nxt in zip(body, body[1:]):
            if (
                isinstance(node, ast.AnnAssign)
                and isinstance(node.target, ast.Name)
                and isinstance(nxt, ast.Expr)
                and isinstance(nxt.value, ast.Constant)
                and isinstance(nxt.value.value, str)
            ):
                out[node.target.id] = " ".join(inspect.cleandoc(nxt.value.value).split())
    return out


def introspect_run_config() -> Introspected:
    """Collect the top-level fields of :class:`RunConfiguration`.

    Returns
    -------
    Introspected
        The fields of the pydantic model.
    """
    from pydantic_core import PydanticUndefined

    from anemoi.inference.config.run import RunConfiguration

    docs = _attribute_docstrings(RunConfiguration)
    result = Introspected(
        kind=TOP_LEVEL_KIND,
        name=TOP_LEVEL_NAME,
        target="anemoi.inference.config.run.RunConfiguration",
        summary=_summary(RunConfiguration.__doc__),
    )
    for name, info in RunConfiguration.model_fields.items():
        if info.default_factory is not None:
            default = info.default_factory()
        elif info.default is PydanticUndefined:
            default = MISSING
        else:
            default = info.default
        annotation = info.annotation if isinstance(info.annotation, str) else inspect.formatannotation(info.annotation)
        result.params[name] = Param(
            name=name,
            annotation=annotation.replace("typing.", ""),
            required=info.is_required(),
            default=default,
            doc=docs.get(name, ""),
        )
    return result


def introspect(kind: str, name: str) -> Introspected:
    """Introspect a component or the top-level configuration.

    Parameters
    ----------
    kind : str
        The component kind, or ``config`` for the top level.
    name : str
        The registered name.

    Returns
    -------
    Introspected
        What the code says about the component.
    """
    if kind == TOP_LEVEL_KIND:
        return introspect_run_config()
    return introspect_component(kind, name)


