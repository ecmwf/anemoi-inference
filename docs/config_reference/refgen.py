"""Build, check and scaffold the anemoi-inference configuration reference.

The reference is driven by hand-curated YAML files:

- ``index.yaml`` lists the component kinds and the registries behind them.
- ``components/<kind>/<name>.yaml`` documents one component (fields, forms, notes).
- ``examples/<kind>/<example>.yaml`` are complete run configurations.

Usage::

    python docs/config_reference/refgen.py check
    python docs/config_reference/refgen.py generate
    python docs/config_reference/refgen.py skeleton inputs mars
    python docs/config_reference/refgen.py build -o docs/_build/config-reference
"""

