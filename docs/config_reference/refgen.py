def load_index() -> dict[str, Any]:
    """Load ``index.yaml``, which declares the documented kinds.

    Returns
    -------
    dict[str, Any]
        The parsed index.
    """
    with open(ROOT / "index.yaml") as f:
        return yaml.safe_load(f)


def normalise(name: str) -> str:
    """Normalise a component name the way the registries do.

    Parameters
    ----------
    name : str
        A component name as written in a configuration.

    Returns
    -------
    str
        The name with underscores replaced by hyphens.
    """
    return name.replace("_", "-")


def load_specs() -> dict[str, dict[str, dict[str, Any]]]:
    """Load every component spec, keyed by kind then by documented name.

    Files starting with an underscore are shared field sets, loaded under their stem.

    Returns
    -------
    dict[str, dict[str, dict[str, Any]]]
        The specs.
    """
    specs: dict[str, dict[str, dict[str, Any]]] = {}
    for path in sorted(COMPONENTS_DIR.glob("*/*.yaml")):
        with open(path) as f:
            spec = yaml.safe_load(f) or {}
        spec.setdefault("name", path.stem)
        spec["_path"] = str(path.relative_to(ROOT))
        specs.setdefault(path.parent.name, {})[path.stem] = spec
    return specs


def find_spec(specs: dict[str, dict[str, dict[str, Any]]], kind: str, name: str) -> dict[str, Any] | None:
    """Find the spec of a component by any of its accepted names.

    Parameters
    ----------
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs, as returned by :func:`load_specs`.
    kind : str
        The component kind.
    name : str
        The name used in a configuration (underscores, hyphens or an alias).

    Returns
    -------
    dict[str, Any] | None
        The spec, or None if no spec matches.
    """
    wanted = normalise(name)
    for key, spec in specs.get(kind, {}).items():
        if key.startswith("_"):
            continue
        names = [spec["name"], *spec.get("aliases", [])]
        if wanted in {normalise(n) for n in names}:
            return spec
    return None


def resolve_fields(spec: dict[str, Any], specs: dict[str, dict[str, dict[str, Any]]]) -> dict[str, dict[str, Any]]:
    """Merge a spec's own fields with the shared field sets it inherits.

    Parameters
    ----------
    spec : dict[str, Any]
        The component spec.
    specs : dict[str, dict[str, dict[str, Any]]]
        All specs, used to resolve ``inherits`` entries such as ``outputs/_common``.

    Returns
    -------
    dict[str, dict[str, Any]]
        Field name to field spec. Own fields come first; inherited fields are flagged with ``inherited_from``.
    """
    fields: dict[str, dict[str, Any]] = {k: dict(v or {}) for k, v in (spec.get("fields") or {}).items()}
    for ref in spec.get("inherits", []) or []:
        kind, _, stem = ref.partition("/")
        base = specs[kind][stem]
        for name, value in resolve_fields(base, specs).items():
            if name not in fields:
                fields[name] = {**value, "inherited_from": ref}
    return fields


@dataclass
class Example:
    """A complete run configuration used as an example.

    Attributes
    ----------
    path : str
        Path relative to the reference root.
    title : str
        First comment line of the file.
    description : str
        Remaining leading comment lines.
    text : str
        The YAML text without the leading comment block.
    data : Any
        The parsed YAML.
    """

    path: str
    title: str
    description: str
    text: str
    data: Any


def load_examples() -> list[Example]:
    """Load every example configuration.

    The leading comment block holds the title (first line) and description (following lines).

    Returns
    -------
    list[Example]
        The examples, sorted by path.
    """
    examples = []
    for path in sorted(EXAMPLES_DIR.glob("**/*.yaml")):
        raw = path.read_text()
        lines = raw.splitlines()
        header = []
        while lines and lines[0].startswith("#"):
            header.append(lines.pop(0)[1:].strip())
        while lines and not lines[0].strip():
            lines.pop(0)
        title = header[0] if header else path.stem
        description = "\n".join(header[1:]).strip()
        examples.append(
            Example(
                path=str(path.relative_to(EXAMPLES_DIR)),
                title=title,
                description=description,
                text="\n".join(lines) + "\n",
                data=yaml.safe_load(raw),
            )
        )
    return examples


